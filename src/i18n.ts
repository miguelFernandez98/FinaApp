import { useSyncExternalStore } from "react";

export type Language = "es" | "en";

let currentLanguage: Language = "es";

const languageListeners = new Set<() => void>();

export function getLanguage(): Language {
  return currentLanguage;
}

export function setLanguage(lang: Language): void {
  if (currentLanguage === lang) return;
  currentLanguage = lang;
  languageListeners.forEach((listener) => listener());
}

export function subscribeLanguage(listener: () => void): () => void {
  languageListeners.add(listener);
  return () => {
    languageListeners.delete(listener);
  };
}

export interface I18nParams {
  [key: string]: string | number;
}

/**
 * Traduce una clave al idioma activo, interpolando parámetros `{key}`.
 * Si la clave no existe, devuelve la propia clave.
 */
export function t(key: string, params?: I18nParams): string {
  const table = messages[currentLanguage] ?? messages.es;
  let str = table[key] ?? messages.es[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.split(`{${k}}`).join(String(v));
    }
  }
  return str;
}

export function useI18n(): { t: typeof t; language: Language } {
  const language = useSyncExternalStore(
    subscribeLanguage,
    getLanguage,
    getLanguage,
  );
  return { t, language };
}


